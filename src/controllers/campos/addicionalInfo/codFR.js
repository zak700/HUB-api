function addValuesToEmp(emp) {
  const output = emp.map((e) => ({
    ...e, content: {
      ...e.content,
      line: e.content.line,
      content: e.content.content.map((tipo11) => {
        if (tipo11.tipoRegistro !== "11") return tipo11
        const { codFontRecursos } = tipo11
        const got = map.get(codFontRecursos.substring(1))
        if (!got) {
          console.log("Valor do codFontRecursos não encontrado:", codFontRecursos.substring(0, 1), codFontRecursos.substring(1))
        }
        const [codFontRecursosMSC, codAEO] = got || ["nan", "nan"]
        return {
          ...tipo11,
          codFontRecursosMSC: codFontRecursos.substring(0, 1) + codFontRecursosMSC,
          codAEO
        }
      })
    }
  }))
  return output
}

const autoSend = (codFontRecursos) => {
  const got = [...(map.get(codFontRecursos.substring(1)) || [null, null])]
  if (!got[0]) {
    console.log("no autoSend found for", codFontRecursos, "in", path.dirname(fileURLToPath(import.meta.url)))
    return got
  }
  got[0] = codFontRecursos.substring(0, 1) + got[0]
  return got
}

export default { addValuesToEmp, map, autoSend }